    public static int coinChange(int[] coins, int amount){

        if(amount == 0) return 0;

        int maxCoins = 0;

        for(int i = coins.length -1; i >= 0; i--) {

            if(coins[i] <= amount) {
                int c = amount / coins[i]; // 2
                maxCoins += c; // 2
                amount -= (coins[i] * c); // 1
            }
        }

        return maxCoins;

    }

